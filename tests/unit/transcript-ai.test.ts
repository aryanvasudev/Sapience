import { describe, expect, it } from "vitest";

import { parseTranscriptAi } from "@/lib/youtube/transcript-ai";

const words = (n: number, from = 0) => Array.from({ length: n }, (_, i) => `w${from + i}`).join(" ");

const SAMPLE = `# Transcript: C++ in 100 Seconds

Source video: https://www.youtube.com/watch?v=MNeX4EGtR5Y
Language: en (auto-generated) · Duration: 2:43 · Words: 553
Interactive version (ask the video, AI summary, chapter outline, notes, subtitle download): https://youtube-transcript.ai/transcript?v=MNeX4EGtR5Y

## Transcript
[0:00] ${words(36)}

[0:30] ${words(18, 36)}

[1:02] last words here
---
Generated by https://youtube-transcript.ai — free YouTube transcript & summary extractor.
[9:99] not a transcript line
`;

describe("parseTranscriptAi", () => {
  it("skips the header and footer and splits paragraphs with times spread across them", () => {
    const lines = parseTranscriptAi(SAMPLE, 70);
    expect(lines).toEqual([
      { seconds: 0, text: words(18) },
      { seconds: 15, text: words(18, 18) },
      { seconds: 30, text: words(18, 36) },
      { seconds: 62, text: "last words here" },
    ]);
  });

  it("joins wrapped paragraph lines and handles h:mm:ss", () => {
    const lines = parseTranscriptAi("## Transcript\n[1:00:05] first part\nsecond part\n[1:00:40] next", 3700);
    expect(lines).toEqual([
      { seconds: 3605, text: "first part second part" },
      { seconds: 3640, text: "next" },
    ]);
  });

  it("merges pieces that land on the same second", () => {
    const lines = parseTranscriptAi(`[0:00] ${words(40)}\n[0:01] end`, 10);
    expect(lines.map((l) => l.seconds)).toEqual([0, 1]);
    expect(lines[0].text.split(" ")).toHaveLength(40);
  });

  it("returns nothing for a response without timestamps", () => {
    expect(parseTranscriptAi("# Transcript: x\n\nNo captions.", 60)).toEqual([]);
  });
});
